/* PHASE 115 — HOME / FINAL COMPOSITION FIX
   An isolated additive patch. Leaves cinematic-home-113.js and
   Work/Sound/Places/About controllers unchanged.
   - remove native legacy World Index overlay/menu
   - remove 01/04 ... badges from the actual DOM, not only via CSS
   - make independent legible chapter labels instead of relying on old
     native World Index link styling
   - maintain original links / keyboard navigation.
*/
(()=>{
  function apply(){
    // The old Step 19 navigation lives OUTSIDE .world-hub. It was missed
    // by all previous .world-hub scoped Index removals. It is redundant
    // since the four native links are now accessible on the Home.
    document.querySelectorAll(".w19-root").forEach(root=>{
      root.querySelectorAll(".w19-trigger,.w19-link").forEach(el=>{
        el.setAttribute("tabindex","-1");
        el.setAttribute("aria-hidden","true");
      });
      root.remove();
    });
    document.querySelectorAll("body > .w19-trigger,body > .w19-backdrop").forEach(el=>el.remove());

    const home=document.querySelector(".world-hub.fi95-ready .fi95-home.fi108-home");
    const cards=[...(home?.querySelectorAll(".fi95-gallery .fi95-panel[data-category]")||[])];
    if(!home||cards.length!==4)return;
    const meta={
      work:["WORK","WEBSITES & DIGITAL EXPERIENCES"],
      sound:["SOUND","MUSIC & INSPIRATION"],
      places:["PLACES","DESTINATIONS & STORIES"],
      about:["ABOUT","THE PERSON BEHIND IT"]
    };
    for(const card of cards){
      // Numbers 01/04 etc were generated by Phase 113 JavaScript.
      // Remove the actual nodes, independent of CSS cache / cascade.
      card.querySelectorAll(".fi95-panel-num,.fi113-panel-id").forEach(el=>el.remove());
      const key=card.dataset.category;
      const info=meta[key];
      if(!info)continue;
      if(!card.querySelector(".fi115-photo-label")){
        const label=document.createElement("div");
        label.className="fi115-photo-label";
        label.setAttribute("aria-hidden","true");
        const name=document.createElement("strong");
        name.className="fi115-photo-name";
        name.textContent=info[0];
        const detail=document.createElement("span");
        detail.className="fi115-photo-detail";
        detail.textContent=info[1];
        label.append(name,detail);
        card.appendChild(label);
      }
    }
    home.classList.add("fi115-clean");
    document.documentElement.classList.add("fi115-index-retired");
  }
  if(document.readyState==="loading")document.addEventListener("DOMContentLoaded",apply,{once:true});
  else apply();
  // In case another old script brings the floating widget back during
  // the document's resource-loading period; no permanent observer.
  window.addEventListener("load",apply,{once:true});
})();
